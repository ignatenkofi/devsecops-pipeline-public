#!/usr/bin/env bash
# Синтетические «утечки» для негатив-прогонов gitleaks — один источник и для
# selftest (текущий пин), и для nightly-bump (кандидат в пины). Пока фикстура
# жила копипастой в двух воркфлоу, она успела протухнуть в одном из них и не
# протухнуть в другом (см. историю ниже).
#
# Почему не канонические AWS-креды из документации. До 2026-07 негатив-прогон
# использовал пару `AKIA…EXAMPLE` из доков AWS (полностью её здесь не пишем —
# см. следующий абзац). Современный gitleaks такие креды намеренно НЕ репортит
# (allowlist на example-значения), поэтому nightly-bump падал три ночи подряд
# на собственном гарде: 8.18.4 их находил, 8.30.1 — уже нет. Проверено
# 2026-07-31 обоими бинарями. Значения ниже находятся и той, и другой версией.
#
# Почему значения собираются из кусков: selftest прогоняет gitleaks по
# собственному репозиторию (позитив, дерево обязано быть чистым). Целая строка,
# совпадающая с правилом, превратила бы этот файл в «утечку» — и позитив-прогон
# упал бы на фикстуре для негатив-прогона.
#
# Это не настоящие секреты: ключи выдуманы, ни один аккаунт им не соответствует.
set -euo pipefail

dir="${1:?usage: secret-fixtures.sh <dir>}"
mkdir -p "$dir"

printf 'aws_access_key_id = %s%s\naws_secret_access_key = %s%s\n' \
  "AKIA" "Z7Y4XQ2WD3NLR5TB" \
  "kT8pQv2mR" "9xLdW3zC7bN5sYhJ4eG1uA6oI0fV" > "$dir/aws.txt"

printf 'GITHUB_TOKEN=%s%s\n' \
  "ghp_" "9fK2mQ7xR4tL8vB3nZ6yC1wD5sH0jE7aP2qU" > "$dir/github-pat.txt"

printf 'SLACK_BOT_TOKEN=%s%s\n' \
  "xoxb-" "2381746509283-4827163904857-Kd93JfLs02mXnQpZaTvBcRyE" > "$dir/slack.txt"

echo "негатив-фикстуры записаны в $dir: aws.txt, github-pat.txt, slack.txt"
